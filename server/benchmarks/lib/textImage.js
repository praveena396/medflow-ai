const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c >>> 0;
  }
  return table;
})();

const crc32 = (buffer) => {
  let crc = 0xffffffff;
  for (const byte of buffer) crc = CRC_TABLE[(crc ^ byte) & 0xff] ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
};

const chunk = (type, data) => {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const typeAndData = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(typeAndData));
  return Buffer.concat([length, typeAndData, crc]);
};

const boxBlur = (pixels, width, height, radius) => {
  const out = Buffer.alloc(pixels.length);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      let sum = 0;
      let count = 0;
      for (let dy = -radius; dy <= radius; dy++) {
        const yy = y + dy;
        if (yy < 0 || yy >= height) continue;
        for (let dx = -radius; dx <= radius; dx++) {
          const xx = x + dx;
          if (xx < 0 || xx >= width) continue;
          sum += pixels[yy * width + xx];
          count++;
        }
      }
      out[y * width + x] = Math.round(sum / count);
    }
  }
  return out;
};

// lines: string[]; scale: pixels per font dot. Returns a grayscale PNG buffer.
export const renderTextPng = (lines, { scale = 6, margin = 24, lineGap = 4, blur = 3 } = {}) => {
  const text = lines.map((line) => line.toUpperCase());
  const maxChars = Math.max(...text.map((line) => line.length), 1);
  const charWidth = 6 * scale; // 5 dots + 1 dot spacing
  const lineHeight = (7 + lineGap) * scale;
  const width = margin * 2 + maxChars * charWidth;
  const height = margin * 2 + text.length * lineHeight;

  const pixels = Buffer.alloc(width * height, 255); // white background
  text.forEach((line, row) => {
    [...line].forEach((char, col) => {
      const glyph = GLYPHS[char] || GLYPHS[' '];
      for (let gy = 0; gy < 7; gy++) {
        for (let gx = 0; gx < 5; gx++) {
          if (glyph[gy][gx] !== '#') continue;
          const x0 = margin + col * charWidth + gx * scale;
          const y0 = margin + row * lineHeight + gy * scale;
          for (let y = y0; y < y0 + scale; y++) pixels.fill(0, y * width + x0, y * width + x0 + scale);
        }
      }
    });
  });

  // A light box blur rounds the blocky dots into strokes OCR reads more like print.
  const blurred = blur > 0 ? boxBlur(pixels, width, height, blur) : pixels;

  // Each scanline starts with filter byte 0 (none).
  const raw = Buffer.alloc((width + 1) * height);
  for (let y = 0; y < height; y++) blurred.copy(raw, y * (width + 1) + 1, y * width, (y + 1) * width);

  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0);
  header.writeUInt32BE(height, 4);
  header[8] = 8; // bit depth
  header[9] = 0; // grayscale
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', header),
    chunk('IDAT', zlib.deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ]);
};
